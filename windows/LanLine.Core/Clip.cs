namespace LanLine.Core;

/// <summary>What clipboard sharing carries (beta.10): text, or a picture as PNG.</summary>
public abstract record ClipContent
{
    public sealed record TextClip(string Text) : ClipContent;
    public sealed record PngClip(byte[] Data) : ClipContent
    {
        public bool Equals(PngClip? o) => o is not null && Data.AsSpan().SequenceEqual(o.Data);
        public override int GetHashCode() => Data.Length;
    }
}

/// <summary>The rules for clipboard sharing, the same on both apps (ClipRules in LanLineCore).</summary>
public static class ClipRules
{
    public const int MaxText = 1_000_000;
    public const int MaxPicture = 10_000_000;
    static readonly byte[] PngMagic = [0x89, 0x50, 0x4E, 0x47];

    /// <summary>Clipboard formats that password managers and other apps add to say "don't copy this anywhere"
    /// (Windows' own clipboard-history exclusions, and the cross-app markers the Mac side also honours).</summary>
    public static readonly HashSet<string> PrivateMarkers = new(StringComparer.OrdinalIgnoreCase)
    {
        "ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore",
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    };

    public static bool Fits(ClipContent c) => c switch
    {
        ClipContent.TextClip t => t.Text.Length > 0 && System.Text.Encoding.UTF8.GetByteCount(t.Text) <= MaxText,
        ClipContent.PngClip p => p.Data.Length <= MaxPicture && p.Data.AsSpan().StartsWith(PngMagic),
        _ => false,
    };

    /// <summary>A stable fingerprint, to skip sending the same thing twice and to ignore our own echo.</summary>
    public static string Fingerprint(ClipContent c) => c switch
    {
        ClipContent.TextClip t => "t:" + Hashing.Sha256Hex(System.Text.Encoding.UTF8.GetBytes(t.Text)),
        ClipContent.PngClip p => "p:" + Hashing.Sha256Hex(p.Data),
        _ => "",
    };

    /// <summary>Should a local clipboard change go out? historyExcluded = the copy says "CanIncludeInClipboardHistory = 0".</summary>
    public static bool ShouldSend(ClipContent? c, IEnumerable<string> formats, bool enabled, bool paused, bool pictures, string? lastFingerprint, bool historyExcluded = false)
    {
        if (!enabled || paused || c == null || historyExcluded) return false;
        if (formats.Any(PrivateMarkers.Contains)) return false;
        if (c is ClipContent.PngClip && !pictures) return false;
        if (!Fits(c)) return false;
        return Fingerprint(c) != lastFingerprint;
    }
}
