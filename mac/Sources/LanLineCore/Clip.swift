import Foundation

/// What clipboard sharing carries (beta.10): text, or a picture as PNG.
public enum ClipContent: Sendable, Equatable {
    case text(String)
    case png(Data)
}

/// The rules for clipboard sharing, the same on both apps (`ClipRules` in LanLine.Core).
public enum ClipRules {
    /// Bigger texts aren't shared (send them as a message instead).
    public static let maxText = 1_000_000
    /// Bigger pictures aren't shared (base64 of 10 MB fits the 16 MiB message limit with room to spare).
    public static let maxPicture = 10_000_000
    static let pngMagic = Data([0x89, 0x50, 0x4E, 0x47])

    /// Clipboard types that password managers and other apps set to say "don't copy this anywhere"
    /// (nspasteboard.org; 1Password; Windows' clipboard-history exclusions are checked by the Windows app).
    public static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    public static func fits(_ c: ClipContent) -> Bool {
        switch c {
        case .text(let t): return !t.isEmpty && t.utf8.count <= maxText
        case .png(let d): return d.count <= maxPicture && d.starts(with: pngMagic)
        }
    }

    /// A stable fingerprint, to skip sending the same thing twice and to ignore our own echo.
    public static func fingerprint(_ c: ClipContent) -> String {
        switch c {
        case .text(let t): return "t:" + Hashing.sha256Hex(Data(t.utf8))
        case .png(let d): return "p:" + Hashing.sha256Hex(d)
        }
    }

    /// Should a local clipboard change go out? Not when sharing is off or paused, not private copies, not what
    /// arrived from the other computer (the echo), not the same thing twice, not what doesn't fit.
    public static func shouldSend(_ c: ClipContent?, types: [String], enabled: Bool, paused: Bool, pictures: Bool,
                                  lastFingerprint: String?) -> Bool {
        guard enabled, !paused, let c else { return false }
        if types.contains(where: privateMarkers.contains) { return false }
        if case .png = c, !pictures { return false }
        guard fits(c) else { return false }
        return fingerprint(c) != lastFingerprint
    }
}
